-- 6. KPI số chuyến lẻ (chia doanh thu khi điều chuyển) — cần dựng lại view phụ thuộc
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'kpi_records' AND column_name = 'completed_shipments'
          AND data_type IN ('integer','smallint','bigint')
    ) THEN
        DROP VIEW IF EXISTS v_leaderboard;
        ALTER TABLE kpi_records
            ALTER COLUMN completed_shipments TYPE NUMERIC(8,1)
            USING completed_shipments::numeric;
    END IF;
END $$;

CREATE OR REPLACE VIEW v_leaderboard AS
SELECT
    k.vehicle_group_id,
    vg.name                     AS vehicle_group_name,
    k.year,
    k.month,
    k.driver_id,
    p.full_name                 AS driver_name,
    k.completed_shipments,
    k.total_revenue,
    k.incident_count,
    RANK() OVER (
        PARTITION BY k.vehicle_group_id, k.year, k.month
        ORDER BY k.total_revenue DESC
    )                           AS revenue_rank,
    RANK() OVER (
        PARTITION BY k.vehicle_group_id, k.year, k.month
        ORDER BY k.completed_shipments DESC
    )                           AS trips_rank
FROM kpi_records k
JOIN profiles p       ON p.id  = k.driver_id
JOIN vehicle_groups vg ON vg.id = k.vehicle_group_id;

