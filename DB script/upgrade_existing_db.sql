CREATE TABLE IF NOT EXISTS shipment_revenue_allocations (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id         INT NOT NULL REFERENCES order_shipments(id) ON DELETE CASCADE,
    driver_id           INT NOT NULL REFERENCES profiles(id),
    share_percent       NUMERIC(5,2) NOT NULL CHECK (share_percent > 0 AND share_percent <= 100),
    allocation_reason   TEXT NOT NULL
                            CHECK (allocation_reason IN ('default_owner','incident_full_transfer','incident_split')),
    incident_id         INT REFERENCES incidents(id) ON DELETE SET NULL,
    created_by          INT REFERENCES profiles(id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shipment_id, driver_id)
);

