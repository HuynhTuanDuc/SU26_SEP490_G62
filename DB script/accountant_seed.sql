-- =============================================================================
-- DATA CONSISTENCY CHECK (sau khi RECONCILE ở mục 20)
-- Mỗi dòng phải trả về count=0, nếu >0 tức là data không nhất quán
-- =============================================================================
SELECT
    '⚠ Debt paid_amount != SUM(confirmed payments) (should be 0)' AS check_name,
    COUNT(*)::TEXT AS mismatches
FROM debts d
WHERE ABS(d.paid_amount - COALESCE((
    SELECT SUM(dp.amount)
    FROM debt_payments dp
    WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
), 0)) > 0.01
UNION ALL
SELECT
    '⚠ Debt status không khớp paid_amount (should be 0)',
    COUNT(*)::TEXT
FROM debts d
WHERE (d.status = 'paid'   AND d.paid_amount < d.total_amount - 0.01)
   OR (d.status = 'partial' AND d.paid_amount <= 0)
   OR (d.status = 'partial' AND d.paid_amount >= d.total_amount - 0.01)
   OR (d.status = 'unpaid'  AND d.paid_amount > 0)
UNION ALL
SELECT
    '⚠ Customer.current_debt != SUM(remaining) (should be 0)',
    COUNT(*)::TEXT
FROM customers c
WHERE ABS(c.current_debt - COALESCE((
    SELECT SUM(GREATEST(d.total_amount - COALESCE((
        SELECT SUM(dp.amount) FROM debt_payments dp
        WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
    ), 0), 0))
    FROM debts d
    WHERE d.customer_id = c.id
      AND d.debt_type = 'customer'
      AND d.status IN ('unpaid', 'partial', 'overdue')
), 0)) > 0.01
ORDER BY check_name;


