-- =========================================

-- ABOUT FIXED IDs IN THIS SEED FILE
-- =========================================
-- Some tables (accounts, profiles, customers, vehicles) use fixed IDs
-- in the seed file (e.g. 100050, 100051, ..., 100200, 100300, ...).
-- Reason:
--   1. Need stable IDs for testing, debugging, documentation
--   2. Subsequent INSERTs (orders, shipments, debts...) use SUBQUERY by
--      email/phone/plate/cargo_name -> do not depend on fixed IDs
--
-- IDENTITY & CONFLICT MECHANISM:
--   All main tables use:
--     id INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000 INCREMENT BY 1)
--   - If INSERT provides id -> use that ID (if not exists)
--   - If INSERT does NOT provide id -> Postgres auto-assigns id = MAX(id) + 1
--
-- WHEN ADDING A NEW RECORD VIA UI / BACKEND:
--   * Backend INSERT will NOT provide id -> sequence auto-assigns
--   * If currently MAX(customer.id) = 100306 -> new record gets id = 100307
--   * If someone deleted record 100302 and inserted a new one (without
--     providing id) -> new id will be 100307 (does NOT reuse 100302)
--   * NO conflict between fixed seed IDs (100300-100306) and auto-generated
--     new IDs (100307, 100308, ...) because sequence only increments
--
-- HOW TO EXTEND SEED WITH NEW USERS/CUSTOMERS/VEHICLES:
--   Recommended: use id > 100500 to avoid clashing with existing range, e.g.:
--     INSERT INTO accounts (id, email, ...) VALUES (100500, 'new@sep490.local', ...);
--   Or omit id column to let sequence assign:
--     INSERT INTO accounts (email, ...) VALUES ('new@sep490.local', ...);
--   Both approaches are safe thanks to ON CONFLICT by email/phone.
--
-- SUMMARY:
--   * Fixed IDs (100xxx) are for seed only, do not affect new records
--   * New records always get the next id from sequence
--   * No conflict thanks to UNIQUE constraint on email/phone
-- =========================================
