-- 32) Đồng bộ current_debt = SUM(open debts) cho customer
-- =============================================================================
UPDATE customers c
SET current_debt = COALESCE((
        SELECT SUM(d.total_amount - d.paid_amount)
        FROM debts d
        WHERE d.customer_id = c.id
          AND d.debt_type = 'customer'
          AND d.status IN ('unpaid','partial','overdue')
    ), 0),
    updated_at = NOW();

-- =============================================================================
-- 33) Đồng bộ paid_amount trên debts theo tổng debt_payments đã confirmed
-- =============================================================================
UPDATE debts d
SET paid_amount = COALESCE((
        SELECT SUM(dp.amount)
        FROM debt_payments dp
        WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
    ), 0),
    status = CASE
        WHEN COALESCE((SELECT SUM(dp.amount) FROM debt_payments dp
                       WHERE dp.debt_id = d.id AND dp.status = 'confirmed'), 0) = 0
            THEN 'unpaid'
        WHEN COALESCE((SELECT SUM(dp.amount) FROM debt_payments dp
                       WHERE dp.debt_id = d.id AND dp.status = 'confirmed'), 0) >= d.total_amount
            THEN 'paid'
        ELSE 'partial'
    END,
    updated_at = NOW()
WHERE d.status IN ('unpaid','partial','overdue');

-- =============================================================================
-- 34) Đồng bộ total_actual_price trên orders theo tổng shipment
-- =============================================================================
UPDATE orders o
SET total_actual_price = COALESCE((
        SELECT SUM(os.actual_price)
        FROM order_shipments os
        WHERE os.order_id = o.id AND os.actual_price IS NOT NULL
    ), 0),
    updated_at = NOW()
WHERE o.derived_status = 'completed' AND o.total_actual_price <> COALESCE((
        SELECT SUM(os.actual_price) FROM order_shipments os
        WHERE os.order_id = o.id AND os.actual_price IS NOT NULL
    ), 0);

-- =============================================================================
-- 35) Đồng bộ driver_debt_deduction trong payroll theo tổng confirmed payments
-- =============================================================================
UPDATE payrolls p
SET driver_debt_deduction = COALESCE((
        SELECT SUM(dp.amount)
        FROM debt_payments dp
        JOIN debts d ON d.id = dp.debt_id
        WHERE d.driver_id = p.driver_id
          AND dp.status = 'confirmed'
          AND DATE_TRUNC('month', dp.confirmed_at) = DATE_TRUNC('month', DATE (p.payroll_year || '-' || p.payroll_month || '-01'))
    ), 0)
WHERE p.status IN ('pending', 'reviewed', 'approved');

-- =============================================================================
-- 20) RECONCILE — đồng bộ lại các cột dẫn xuất từ debt_payments/debts
-- =============================================================================
-- Sau khi insert debts + debt_payments ở trên, cần đảm bảo:
--   * debts.paid_amount  = SUM(confirmed debt_payments.amount) theo debt
--   * debts.status        = paid | partial | unpaid (theo paid vs total)
--   * customers.current_debt = SUM(remaining) của mọi customer debt
--
-- Khối này idempotent — chạy nhiều lần cũng ra cùng kết quả.
UPDATE debts d SET
    paid_amount = COALESCE((
        SELECT SUM(dp.amount)
        FROM debt_payments dp
        WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
    ), 0),
    status = CASE
        WHEN COALESCE((
            SELECT SUM(dp.amount) FROM debt_payments dp
            WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
        ), 0) >= d.total_amount - 0.01 THEN 'paid'
        WHEN COALESCE((
            SELECT SUM(dp.amount) FROM debt_payments dp
            WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
        ), 0) > 0 THEN 'partial'
        ELSE 'unpaid'
    END,
    updated_at = NOW()
WHERE d.debt_type IN ('customer', 'driver', 'partner');

-- Đồng bộ current_debt cho từng customer
UPDATE customers c SET
    current_debt = COALESCE((
        SELECT SUM(d.total_amount - COALESCE((
            SELECT SUM(dp.amount) FROM debt_payments dp
            WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
        ), 0))
        FROM debts d
        WHERE d.customer_id = c.id
          AND d.debt_type = 'customer'
          AND d.status IN ('unpaid', 'partial', 'overdue')
          AND (d.total_amount - COALESCE((
              SELECT SUM(dp.amount) FROM debt_payments dp
              WHERE dp.debt_id = d.id AND dp.status = 'confirmed'
          ), 0)) > 0
    ), 0),
    updated_at = NOW();

