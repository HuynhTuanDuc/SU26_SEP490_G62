-- Yêu cầu hoàn tác tầng 2: người làm sai xin lùi, người có quyền duyệt.
--
-- Các thao tác tầng 2 (gỡ duyệt chi phí, huỷ xác nhận khoản nộp, gỡ hoàn thành chuyến)
-- đều đụng tới tiền. Để ai có quyền là tự làm tự lùi thì chính người bấm nhầm sẽ tự gỡ
-- và không ai biết — đó là chỗ dễ bị lạm dụng nhất.
--
-- Bảng này KHÔNG tự thực hiện việc lùi. Nó ghi lại "ai xin lùi cái gì, vì sao, ai quyết,
-- quyết lúc nào"; việc lùi vẫn do đúng service nghiệp vụ làm, vì chỉ nó biết phải dọn
-- những gì kèm theo.
CREATE TABLE reversal_requests (
    id           INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000 INCREMENT BY 1) PRIMARY KEY,

    -- Khoá trong sổ đăng ký của reversalService, vd 'expense.approve'. Cố ý để TEXT
    -- không CHECK: thêm một loại thao tác lùi là việc của mã nguồn, không nên phải chạy
    -- migration. Mã đã từ chối khoá lạ ngay ở cửa vào.
    kind         TEXT NOT NULL,
    entity_type  TEXT NOT NULL,
    entity_id    INT  NOT NULL,

    reason       TEXT NOT NULL CHECK (btrim(reason) <> ''),
    requested_by INT  NOT NULL REFERENCES profiles(id),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    status       TEXT NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending', 'approved', 'rejected', 'cancelled')),

    decided_by      INT REFERENCES profiles(id),
    decided_at      TIMESTAMPTZ,
    decision_note   TEXT,

    -- Tách khỏi status vì "đã duyệt" và "đã lùi xong" là hai việc: duyệt xong mà service
    -- nghiệp vụ từ chối (khoản đã chi mất rồi) thì yêu cầu vẫn approved nhưng không có gì
    -- được lùi — phải nhìn thấy được điều đó.
    executed_at     TIMESTAMPTZ,
    execution_error TEXT,

    CONSTRAINT reversal_requests_decided_together CHECK (
        (status = 'pending' AND decided_by IS NULL AND decided_at IS NULL)
        OR (status <> 'pending' AND decided_by IS NOT NULL AND decided_at IS NOT NULL)
    )
);

