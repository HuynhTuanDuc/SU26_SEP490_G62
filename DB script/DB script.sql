CREATE TABLE accounts (
    id              INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000 INCREMENT BY 1) PRIMARY KEY,
    -- Email KHÔNG bắt buộc: phần lớn tài xế không có email, bắt buộc chỉ khiến người
    -- nhập bịa địa chỉ giả cho qua form. Định danh đăng nhập có thể là email HOẶC số
    -- điện thoại (profiles.phone) — xem backend/utils/loginIdentifier.js.
    -- UNIQUE vẫn chặn trùng email thật; Postgres coi mỗi NULL là khác nhau nên nhiều
    -- tài khoản cùng để trống không hề đụng nhau. CHECK bên dưới cấm chuỗi rỗng để
    -- "không có email" chỉ có đúng một cách biểu diễn là NULL.
    email           TEXT UNIQUE,
    password_hash   TEXT NOT NULL,
    role_id         INT NOT NULL REFERENCES roles(id),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    last_login_at   TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_accounts_email_not_blank CHECK (email IS NULL OR btrim(email) <> '')
);

