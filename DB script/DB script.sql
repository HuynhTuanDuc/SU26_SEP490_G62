-- Lưu vết mỗi lần đọc hóa đơn bằng AI: nguyên văn model đọc được + kết luận của từng
-- lớp kiểm tra. Tách hai cột là có chủ đích — raw_extraction là "máy đọc được gì",
-- checks là "hệ thống kết luận gì". Cần cho tranh chấp, cho việc đo độ chính xác thật,
-- và cho vòng phản hồi khi người duyệt ghi đè phán quyết của máy.
CREATE TABLE receipt_extractions (
    id              INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000 INCREMENT BY 1) PRIMARY KEY,
    entity_type     TEXT NOT NULL CHECK (entity_type IN ('maintenance_record', 'expense')),
    entity_id       INT,
    image_url       TEXT NOT NULL,
    -- Băm nội dung ảnh, dùng để chặn nộp lại đúng một tấm ảnh.
    image_sha256    TEXT,
    provider        TEXT,
    model           TEXT,
    prompt_version  TEXT,
    raw_extraction  JSONB,
    checks          JSONB NOT NULL DEFAULT '[]'::jsonb,
    verdict         TEXT NOT NULL
                        CHECK (verdict IN ('passed', 'needs_review', 'rejected', 'error')),
    claimed_amount  NUMERIC(12,2),
    receipt_total   NUMERIC(12,2),
    latency_ms      INT,
