-- ── Kỳ ghi nhận doanh thu ───────────────────────────────────────────────────
-- Phải đặt SAU business_report_periods: hàm bên dưới đọc bảng đó và Postgres kiểm
-- tra thân hàm SQL ngay lúc CREATE.

-- Kỳ ghi nhận cho một chuyến hoàn thành lúc p_completed_at: tháng của chính nó nếu
-- kỳ đó còn mở, ngược lại là kỳ MỞ SỚM NHẤT kế tiếp. business_report_periods chỉ
-- chứa kỳ đã ký duyệt nên "có dòng" = "đã khoá". generate_series + MIN xử lý đúng cả
-- chuỗi nhiều tháng đã ký liên tiếp lẫn trường hợp thủng ở giữa. Trần 120 tháng chỉ
-- để chặn vòng lặp vô hạn nếu dữ liệu bẩn.
CREATE OR REPLACE FUNCTION fn_revenue_recognition_period(p_completed_at TIMESTAMPTZ)
RETURNS DATE
LANGUAGE sql
STABLE
AS $$
    WITH base AS (
        SELECT date_trunc('month', p_completed_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::date AS p
    )
    SELECT COALESCE(
        (
            SELECT MIN(g.p)::date
            FROM base,
                 generate_series(base.p, base.p + INTERVAL '120 months', INTERVAL '1 month') g(p)
            WHERE NOT EXISTS (
                SELECT 1 FROM business_report_periods brp
                WHERE make_date(brp.period_year, brp.period_month, 1) = g.p::date
            )
        ),
        (SELECT p FROM base)
    );
$$;

CREATE OR REPLACE FUNCTION trg_set_revenue_period() RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_recompute BOOLEAN := FALSE;
BEGIN
    IF NEW.status = 'completed' AND NEW.completed_at IS NOT NULL THEN
        IF TG_OP = 'INSERT' THEN
            v_recompute := TRUE;
        ELSE
            v_recompute := OLD.status       IS DISTINCT FROM 'completed'
                        OR OLD.completed_at IS DISTINCT FROM NEW.completed_at
                        OR (OLD.actual_price IS NULL AND NEW.actual_price IS NOT NULL);
        END IF;
    END IF;

    IF v_recompute THEN
        NEW.revenue_period := fn_revenue_recognition_period(NEW.completed_at);
    END IF;
    RETURN NEW;
END;
$$;

